"""Generate the backend error directory from the bundled authoritative contract."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "build/openapi/openapi.bundled.json"
TARGET = ROOT / "services/backend/src/backend_app/core/error_catalog.py"


def build_catalog(document: dict[str, Any]) -> str:
    if not str(document.get("openapi", "")).startswith("3.1."):
        raise ValueError("The contract must use OpenAPI 3.1")
    version = document["info"]["version"]
    if not isinstance(version, str):
        raise ValueError("The contract revision must be a string")
    request_id_pattern = document["components"]["schemas"]["RequestId"]["pattern"]
    if not isinstance(request_id_pattern, str):
        raise ValueError("Request ID pattern must be a string")
    re.compile(request_id_pattern)
    problem = document["components"]["schemas"]["ProblemDetails"]
    prefix = problem["x-error-type-prefix"]
    if not isinstance(prefix, str) or not urlsplit(prefix).scheme:
        raise ValueError("Error type prefix must be an absolute URI prefix")
    catalog = problem["x-error-catalog"]
    if not isinstance(catalog, dict) or not catalog:
        raise ValueError("Error catalog must be a nonempty object")
    definitions: dict[str, tuple[int | None, str]] = {}
    legacy_codes = {"VALIDATION_ERROR", "INTERNAL_ERROR", "HTTP_ERROR"}
    for domain, errors in catalog.items():
        if not isinstance(domain, str) or not isinstance(errors, dict):
            raise ValueError("Error domains must contain objects")
        for code, definition in errors.items():
            if not isinstance(code, str) or code in definitions:
                raise ValueError(f"Invalid or duplicate error code: {code}")
            if code not in legacy_codes and (
                not code.startswith(domain + ".")
                or not re.fullmatch(r"[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*", code)
            ):
                raise ValueError(f"Error code must belong to its domain: {code}")
            if not isinstance(definition, dict):
                raise ValueError(f"Invalid error definition: {code}")
            status, title = definition.get("status"), definition.get("title")
            if status is None:
                if code != "HTTP_ERROR":
                    raise ValueError(f"Only the HTTP fallback may have a variable status: {code}")
            elif type(status) is not int or not 400 <= status <= 599:
                raise ValueError(f"Invalid HTTP error status: {code}")
            if not isinstance(title, str) or not title.strip():
                raise ValueError(f"Public error title is required: {code}")
            definitions[code] = (status, title)

    lines = [
        "# Generated by scripts/build_error_catalog.py; do not edit manually.",
        "from typing import Final",
        "",
        f"CONTRACT_VERSION: Final[str] = {json.dumps(version)}",
        f"ERROR_TYPE_PREFIX: Final[str] = {json.dumps(prefix)}",
        f"REQUEST_ID_PATTERN: Final[str] = {json.dumps(request_id_pattern)}",
        "ERROR_CATALOG: Final[dict[str, tuple[int | None, str]]] = {",
    ]
    for code, (status, title) in sorted(definitions.items()):
        lines.append(
            f"    {json.dumps(code)}: ({status!r}, {json.dumps(title, ensure_ascii=False)}),"
        )
    lines.extend(["}", ""])
    return "\n".join(lines)


def check_catalog(document: dict[str, Any]) -> None:
    if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != build_catalog(document):
        raise AssertionError("Generated error catalog is stale; run `pnpm api:generate-errors`")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    document: object = json.loads(BUNDLE.read_text(encoding="utf-8"))
    if not isinstance(document, dict):
        raise ValueError("OpenAPI bundle must be an object")
    if options.check:
        check_catalog(document)
    else:
        TARGET.write_text(build_catalog(document), encoding="utf-8")
        print("Generated backend error catalog")


if __name__ == "__main__":
    main()
